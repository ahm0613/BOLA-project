SELECT n.id, p.id, 1 + floor(random() * 2)::int
  FROM new_users n
 CROSS JOIN LATERAL (
       SELECT id FROM products
        WHERE n.id > 0                      -- 사용자마다 따로 뽑도록 바깥 행을 참조
